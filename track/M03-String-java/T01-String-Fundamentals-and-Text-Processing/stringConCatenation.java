public class stringConCatenation {
    public static void main(String[] args) {
        String s1="Software ";
        String s2="Developer";
        String s3=s1+s2;
        System.out.println(s3);

        String t1=new String ("Java ");
        String t2=new String ("Developer");
        String result=t1.concat(t2);
        System.out.println(result);
    }
}
